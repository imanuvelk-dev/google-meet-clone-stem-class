/**
 * Generates src/design/primitives/icon-paths.ts from Material Symbols.
 *
 * The Figma names its icon groups mic_off, more_vert, videocam and so on, which
 * are Material Symbols names, so this is the set the design actually references
 * rather than a lookalike. Unlike Product Sans, Material Symbols is Apache-2.0
 * and safe to ship.
 *
 * Paths are extracted and committed, so nothing hand-draws an approximation and
 * no icon font is fetched at runtime. Only the glyphs we use are included.
 *
 * Weight 600, not the 400 default: measured off the Figma renders, not guessed.
 * See the icon weight entry in docs/DECISIONS.md.
 *
 * Run: npm run icons:build
 */
import { readFile, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const ROOT = join(import.meta.dirname, '..')
const SOURCE = join(ROOT, 'node_modules', '@material-symbols', 'svg-600', 'outlined')
const OUTPUT = join(ROOT, 'src', 'design', 'primitives', 'icon-paths.ts')

/** Every glyph Phase 1 needs. Add here rather than importing the whole set. */
const ICONS = [
  'mic',
  'mic_off',
  'videocam',
  'videocam_off',
  'more_vert',
  'volume_up',
  // The Figma names these exactly: arrow_drop_down on the device pickers,
  // keyboard_arrow_up on "Show fewer options". They are different glyphs.
  'arrow_drop_down',
  'keyboard_arrow_up',
  'keyboard_arrow_down',
  'close',
  'error',
  'present_to_all',
  'account_box',
  'devices',
  'link',
  'content_copy',
  'signal_cellular_alt',
  'settings',
  'add',
  'keyboard',

  /*
   * The in-call bar. The Figma's `Desktop / Meeting / Light` names these groups
   * itself, so they are the design's own references rather than lookalikes we
   * picked: computer_arrow_up on Screen Share, mood on Reaction, closed_caption,
   * back_hand on Raised Hands, call_end on Leave Call, and info / group / chat /
   * lock_person along the right. radio_button_checked is Meet's recording glyph,
   * used by the overflow menu's Start/Stop recording item.
   */
  'computer_arrow_up',
  'mood',
  'closed_caption',
  'back_hand',
  'call_end',
  'info',
  'group',
  'chat',
  'lock_person',
  'radio_button_checked',
  // edit_square is Meet's whiteboard glyph, used by the overflow menu's
  // Whiteboard / Close whiteboard item.
  'edit_square',

  /*
   * The stage. `keep` is Material's pin glyph - there is no `push_pin` in this
   * set. `person` is the camera-off avatar fallback.
   */
  'keep',
  'keep_off',
  'person',
  'arrow_back',
  'arrow_forward',

  /*
   * Layout switcher. Material ships no spotlight glyph, so `fullscreen` stands
   * in for it; grid_view and view_sidebar are exact.
   */
  'grid_view',
  'view_sidebar',
  'fullscreen',

  /*
   * The Chat and People panels. The Figma names `send` and `search` itself, so
   * both are the design's own references. `person_remove` is not in either
   * frame - removing someone is a host action sourced from live Meet, and the
   * frames draw resting states only.
   */
  'send',
  'search',
  'person_remove',

  'help',
  'feedback',
  'chevron_left',
  'chevron_right',
]

const PATH_D = /<path d="([^"]+)"/
const VIEWBOX = /viewBox="([^"]+)"/

async function main() {
  const entries: string[] = []
  let viewBox = ''

  for (const name of ICONS) {
    const svg = await readFile(join(SOURCE, `${name}.svg`), 'utf8')

    const path = PATH_D.exec(svg)?.[1]
    if (!path) throw new Error(`No path found in ${name}.svg`)

    // Material Symbols uses a 0 -960 960 960 box, not the usual 0 0 24 24.
    // Getting this wrong renders an empty icon, so assert it rather than assume.
    const box = VIEWBOX.exec(svg)?.[1]
    if (!box) throw new Error(`No viewBox in ${name}.svg`)
    if (viewBox && box !== viewBox) {
      throw new Error(`${name}.svg has viewBox ${box}, expected ${viewBox}`)
    }
    viewBox = box

    entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(path)},`)
  }

  const source = `// GENERATED by \`npm run icons:build\`. Do not hand-edit.
//
// Material Symbols (Apache-2.0), outlined, weight 600. Only the glyphs we use.
// The Figma references these by name (mic_off, more_vert), so they are the real
// set rather than a lookalike.

export const ICON_VIEW_BOX = ${JSON.stringify(viewBox)}

export const ICON_PATHS = {
${entries.join('\n')}
} as const

export type IconName = keyof typeof ICON_PATHS
`

  await writeFile(OUTPUT, source)
  console.log(`icon-paths.ts: ${ICONS.length} icons, viewBox ${viewBox}`)
}

await main()
