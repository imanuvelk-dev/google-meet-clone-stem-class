/**
 * Turns figma-cli's extracted DESIGN.md into our design tokens.
 *
 * The Figma file has no variables, so `extract` synthesises names by usage
 * frequency: accent, accent-2, text-primary-5. Those are exact in value but
 * meaningless in intent, and they renumber whenever the design changes. So we
 * never emit them. Instead a hand-owned map says what each value MEANS, and the
 * extracted palette is used to verify those values still exist.
 *
 * That inverts the usual drift problem: rather than trusting a generated name to
 * stay stable, we pin the value and let the build fail loudly when it moves.
 */

export interface TypographyStyle {
  fontFamily: string
  fontSize: number
  fontWeight: number
  lineHeight: number
  letterSpacing?: number
}

export interface DesignTokens {
  color: Record<string, string>
  radius: Record<string, string>
  typography: Record<string, TypographyStyle>
}

export interface FontFace {
  family: string
  weight: number
}

/**
 * Figma reports weight through the family name ("Product Sans Medium") and
 * leaves fontWeight at 400. Our @font-face declares one family with real
 * weights, so emitting Figma's shape verbatim would request weight 400 of a
 * family that does not exist, and the browser would synthesise something close
 * but wrong.
 *
 * SF Pro appears on the iOS frames. It is Apple-licensed and never shipped, so
 * it collapses to the system stack, which is what SF Pro means on Apple devices
 * anyway. See CLAUDE.md.
 */
const FAMILY_SUFFIX_WEIGHTS: ReadonlyArray<[string, number]> = [
  [' Thin', 100],
  [' Light', 300],
  [' Medium', 500],
  [' Bold', 700],
  [' Black', 900],
]

export function normalizeFontFace(fontFamily: string, fontWeight: number): FontFace {
  if (fontFamily.startsWith('SF Pro')) return { family: 'system-ui', weight: fontWeight }

  for (const [suffix, weight] of FAMILY_SUFFIX_WEIGHTS) {
    if (fontFamily.endsWith(suffix)) {
      return { family: fontFamily.slice(0, -suffix.length), weight }
    }
  }

  return { family: fontFamily, weight: fontWeight }
}

/** Our semantic name -> the exact value it must resolve to in Figma. */
export type TokenMap = Record<string, string>

const TOKEN_BLOCK = /```json design-tokens\s*\n([\s\S]*?)```/

export function parseDesignTokens(markdown: string): DesignTokens {
  const match = TOKEN_BLOCK.exec(markdown)
  if (!match?.[1]) {
    throw new Error(
      'No `json design-tokens` block in DESIGN.md. Re-run `npm run figma:pull` with Figma connected.',
    )
  }

  const parsed = JSON.parse(match[1]) as Partial<DesignTokens>
  return {
    color: parsed.color ?? {},
    radius: parsed.radius ?? {},
    typography: parsed.typography ?? {},
  }
}

const HEADER = `/**
 * GENERATED by \`npm run tokens:build\` from the Figma file. Do not hand-edit:
 * your changes will be overwritten on the next pull.
 *
 * To change a token, edit scripts/token-map.json, which records what each Figma
 * value means. Values here are verified to still exist in the design.
 */`

export function buildTokensCss(tokens: DesignTokens, map: TokenMap): string {
  const known = new Set(
    [...Object.values(tokens.color), ...Object.values(tokens.radius)].map((v) => v.toLowerCase()),
  )

  const drifted = Object.entries(map).filter(([, value]) => !known.has(value.toLowerCase()))
  if (drifted.length > 0) {
    const detail = drifted.map(([name, value]) => `  ${name}: ${value}`).join('\n')
    throw new Error(
      `These tokens no longer exist in the Figma file:\n${detail}\n\n` +
        'The design changed, or the value was retired. Update scripts/token-map.json.',
    )
  }

  const declarations = Object.entries(map)
    .map(([name, value]) => `  --${name}: ${value};`)
    .join('\n')

  return `${HEADER}\n\n:root {\n${declarations}\n}\n`
}

/**
 * Emits the type ramp. Our semantic role -> the Figma style key it comes from.
 *
 * The map exists for the same reason as the colour one: extract names the ramp
 * body-2 through body-7 by usage frequency, which tells a component author
 * nothing and renumbers on the next pull.
 */
export function buildTypographyCss(
  typography: Record<string, TypographyStyle>,
  map: Record<string, string>,
): string {
  const declarations: string[] = []

  for (const [name, styleKey] of Object.entries(map)) {
    const style = typography[styleKey]
    if (!style) {
      throw new Error(
        `Typography style "${styleKey}" (mapped to ${name}) is not in the Figma file. ` +
          'The design changed, or the style was retired. Update scripts/token-map.json.',
      )
    }

    const { family, weight } = normalizeFontFace(style.fontFamily, style.fontWeight)
    const stack =
      family === 'system-ui' ? 'system-ui, sans-serif' : `'${family}', Roboto, sans-serif`

    declarations.push(`  --${name}-family: ${stack};`)
    declarations.push(`  --${name}-size: ${style.fontSize}px;`)
    declarations.push(`  --${name}-weight: ${weight};`)
    declarations.push(`  --${name}-line-height: ${style.lineHeight}px;`)
    if (typeof style.letterSpacing === 'number') {
      declarations.push(`  --${name}-letter-spacing: ${style.letterSpacing}px;`)
    }
  }

  return declarations.join('\n')
}

/** Types so a typo in a token name is a compile error, not a silent no-op. */
export function buildTokensDts(map: TokenMap): string {
  const union = Object.keys(map)
    .map((name) => `  | '--${name}'`)
    .join('\n')

  return `// GENERATED by \`npm run tokens:build\`. Do not hand-edit.\n\nexport type TokenName =\n${union}\n`
}
